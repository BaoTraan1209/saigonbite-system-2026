CREATE DATABASE IF NOT EXISTS saigonbite CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE saigonbite;

CREATE TABLE hubs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE,
 address VARCHAR(255) NOT NULL, phone VARCHAR(30) NULL, capacity INT UNSIGNED NOT NULL DEFAULT 20,
 status ENUM('DRAFT','ACTIVE','SUSPENDING','SUSPENDED','ARCHIVED') NOT NULL DEFAULT 'DRAFT',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE brands (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE,
 description TEXT NULL, status ENUM('ACTIVE','INACTIVE','ARCHIVED') NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE hub_brands (hub_id BIGINT UNSIGNED NOT NULL, brand_id BIGINT UNSIGNED NOT NULL, PRIMARY KEY(hub_id,brand_id), FOREIGN KEY(hub_id) REFERENCES hubs(id), FOREIGN KEY(brand_id) REFERENCES brands(id)) ENGINE=InnoDB;
CREATE TABLE menu_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, brand_id BIGINT UNSIGNED NOT NULL, name VARCHAR(150) NOT NULL,
 description TEXT NULL, price DECIMAL(12,2) NOT NULL, status ENUM('ACTIVE','INACTIVE','ARCHIVED') NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(brand_id) REFERENCES brands(id)
) ENGINE=InnoDB;
CREATE TABLE hub_menu_items (hub_id BIGINT UNSIGNED NOT NULL, menu_item_id BIGINT UNSIGNED NOT NULL, is_available TINYINT(1) NOT NULL DEFAULT 1, PRIMARY KEY(hub_id,menu_item_id), FOREIGN KEY(hub_id) REFERENCES hubs(id), FOREIGN KEY(menu_item_id) REFERENCES menu_items(id)) ENGINE=InnoDB;
CREATE TABLE orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_code VARCHAR(32) NOT NULL UNIQUE,
 customer_name VARCHAR(120) NOT NULL, customer_phone VARCHAR(30) NOT NULL, hub_id BIGINT UNSIGNED NOT NULL,
 brand_id BIGINT UNSIGNED NOT NULL, delivery_address VARCHAR(255) NOT NULL,
 payment_method ENUM('CASH_ON_DELIVERY','CARD','ONLINE') NOT NULL,
 subtotal DECIMAL(12,2) NOT NULL, delivery_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
 discount DECIMAL(12,2) NOT NULL DEFAULT 0, total DECIMAL(12,2) NOT NULL,
 status ENUM('SUBMITTED','ACCEPTED','PREPARING','READY','PICKED_UP','DELIVERED','DELIVERY_FAILED','REJECTED','CANCELLED') NOT NULL DEFAULT 'SUBMITTED',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(hub_id) REFERENCES hubs(id), FOREIGN KEY(brand_id) REFERENCES brands(id), INDEX idx_orders_status(status), INDEX idx_orders_hub_status(hub_id,status)
) ENGINE=InnoDB;
CREATE TABLE order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, menu_item_id BIGINT UNSIGNED NOT NULL,
 item_name VARCHAR(150) NOT NULL, quantity INT UNSIGNED NOT NULL, unit_price DECIMAL(12,2) NOT NULL, line_total DECIMAL(12,2) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE, FOREIGN KEY(menu_item_id) REFERENCES menu_items(id)
) ENGINE=InnoDB;
CREATE TABLE deliveries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL UNIQUE,
 shipper_name VARCHAR(120) NULL, shipper_phone VARCHAR(30) NULL,
 status ENUM('WAITING_PICKUP','PICKED_UP','DELIVERED','FAILED') NOT NULL DEFAULT 'WAITING_PICKUP',
 failure_reason VARCHAR(255) NULL, cod_collected DECIMAL(12,2) NOT NULL DEFAULT 0,
 delivered_at DATETIME NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE activity_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor VARCHAR(100) NULL, action VARCHAR(100) NOT NULL,
 entity_type VARCHAR(80) NOT NULL, entity_id BIGINT UNSIGNED NULL, details JSON NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

